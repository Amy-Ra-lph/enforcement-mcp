"""SELinux remediation playbook generator.

Generates Ansible playbooks using fedora.linux_system_roles for SELinux
denials, file context mismatches, fapolicyd blocks, and AIDE changes.
Read-only: returns YAML text, never executes.

Each finding type produces ranked fix alternatives sorted by risk score
(safest first). Every alternative includes risk assessment and rollback
instructions.
"""

from __future__ import annotations

import typing as t

import yaml
from mcp.types import ToolAnnotations
from pydantic import Field

from linux_mcp_server.audit import log_tool_call
from linux_mcp_server.server import mcp
from linux_mcp_server.utils.types import Host
from linux_mcp_server.utils.validation import validate_path

SYSTEM_ROLES_COLLECTION = "fedora.linux_system_roles"

# --- Risk scoring (subset of enforcement-mcp risk engine) ---

SENSITIVE_TYPES = {
    "shadow_t": 30, "sshd_key_t": 30, "passwd_file_t": 25,
    "etc_t": 15, "bin_t": 20, "sbin_t": 20,
    "httpd_config_t": 15, "mysqld_db_t": 20,
}
HIGH_RISK_PERMISSIONS = {
    "execmem": 20, "relabelto": 25, "relabelfrom": 25,
    "transition": 15, "associate": 10,
}
FAPOLICYD_PATH_RISK = {
    "/tmp": 30, "/var/tmp": 30, "/dev/shm": 30,
    "/root": 25, "/home": 15,
}


def _score_boolean(rules_unlocked: int, domains_affected: int) -> int:
    score = min(rules_unlocked * 3, 40) + min(domains_affected * 5, 30)
    return min(score, 100)


def _score_module(target_type: str, permission: str) -> int:
    score = 3
    score += SENSITIVE_TYPES.get(target_type, 0)
    score += HIGH_RISK_PERMISSIONS.get(permission, 0)
    return min(score, 100)


def _score_fapolicyd_trust(path: str) -> dict:
    base = 10
    for prefix, penalty in FAPOLICYD_PATH_RISK.items():
        if path.startswith(prefix):
            base += penalty
            break
    level = "low" if base <= 25 else "medium" if base <= 50 else "high"
    return {
        "risk_score": min(base, 100),
        "risk_level": level,
        "recommendation": "proceed" if base <= 25 else "proceed_with_review",
    }


def _risk_comment(risk: dict) -> str:
    level = risk.get("risk_level", "unknown")
    score = risk.get("risk_score", -1)
    rec = risk.get("recommendation", "unknown")
    return f"Risk: {level} ({score}/100) — {rec}"


def _playbook_header(description: str) -> dict:
    return {
        "name": description,
        "hosts": "{{ target_hosts }}",
        "become": True,
    }


def _render_playbook(play: dict, description: str, risk: dict) -> str:
    comment = _risk_comment(risk)
    playbook_yaml = yaml.dump([play], default_flow_style=False, sort_keys=False)
    return (
        f"# Remediation: {description}\n"
        f"# {comment}\n"
        f"# Generated by linux-mcp — review before applying\n"
        f"---\n{playbook_yaml}"
    )


def _validate_selinux_identifier(value: str, param: str) -> str:
    """Validate SELinux type/class/permission identifiers."""
    import re
    if not re.match(r"^[a-zA-Z_][a-zA-Z0-9_.\-]*$", value):
        raise ValueError(f"Invalid {param}: {value!r}")
    return value


# --- Tool registration ---

@mcp.tool(
    title="Generate SELinux remediation playbook",
    description=(
        "Generate an Ansible remediation playbook using linux-system-roles. "
        "Read-only: returns YAML text with risk assessment, never executes. "
        "Ranks fix options from narrowest scope to broadest."
    ),
    tags={"fixed", "selinux", "security", "remediation"},
    annotations=ToolAnnotations(readOnlyHint=True),
)
@log_tool_call
async def generate_selinux_playbook(
    finding_type: t.Annotated[
        str,
        Field(description="Type: 'denial', 'file_context', 'fapolicyd_block', 'aide_change'"),
    ],
    host: Host,
    source_type: t.Annotated[
        str | None, Field(description="SELinux source type (for denial)")
    ] = None,
    target_type: t.Annotated[
        str | None, Field(description="SELinux target type (for denial)")
    ] = None,
    tclass: t.Annotated[
        str | None, Field(description="Object class (for denial)")
    ] = None,
    permission: t.Annotated[
        str | None, Field(description="Permission (for denial)")
    ] = None,
    path: t.Annotated[
        str | None, Field(description="File path (any finding type)")
    ] = None,
    expected_type: t.Annotated[
        str | None, Field(description="Expected SELinux type (for file_context)")
    ] = None,
    actual_type: t.Annotated[
        str | None, Field(description="Actual SELinux type (for file_context)")
    ] = None,
) -> dict:
    """Generate remediation playbook with risk assessment."""
    if finding_type == "denial":
        return await _remediate_denial(
            host, source_type, target_type, tclass, permission, path,
        )
    elif finding_type == "file_context":
        return _remediate_file_context(path, expected_type, actual_type)
    elif finding_type == "fapolicyd_block":
        return _remediate_fapolicyd(path)
    elif finding_type == "aide_change":
        return _remediate_aide()
    else:
        return {
            "error": "unknown_finding_type",
            "finding_type": finding_type,
            "supported": ["denial", "file_context", "fapolicyd_block", "aide_change"],
        }


async def _remediate_denial(
    host: Host,
    source_type: str | None,
    target_type: str | None,
    tclass: str | None,
    permission: str | None,
    path: str | None,
) -> dict:
    if not all([source_type, target_type, tclass, permission]):
        return {
            "error": "missing_params",
            "required": ["source_type", "target_type", "tclass", "permission"],
        }

    try:
        source = _validate_selinux_identifier(source_type, "source_type")
        target = _validate_selinux_identifier(target_type, "target_type")
        cls = _validate_selinux_identifier(tclass, "tclass")
        perm = _validate_selinux_identifier(permission, "permission")
        if path:
            validate_path(path)
    except ValueError as e:
        return {"error": "invalid_input", "detail": str(e)}

    alternatives = []

    if path:
        relabel_play = _playbook_header(f"Relabel {path} for {source} access")
        relabel_play["roles"] = [{
            "role": f"{SYSTEM_ROLES_COLLECTION}.selinux",
            "vars": {"selinux_restore_dirs": [path]},
        }]
        relabel_risk = {
            "risk_score": 0, "risk_level": "low",
            "recommendation": "proceed",
            "reversibility": {
                "method": "restorecon is idempotent — no policy change",
                "difficulty": "trivial",
            },
        }
        alternatives.append({
            "strategy": "relabel",
            "scope": "narrowest — fixes one file, no policy change",
            "risk": relabel_risk,
            "playbook": _render_playbook(
                relabel_play, f"Relabel {path} to expected context", relabel_risk,
            ),
        })

    # Boolean lookup via sesearch on the remote host
    from linux_mcp_server.commands import get_command
    import shlex
    cmd = get_command("selinux_sesearch_boolean")
    try:
        returncode, stdout, _ = await cmd.run(
            host=host,
            source=shlex.quote(source),
            target=shlex.quote(target),
            tclass=shlex.quote(cls),
            permission=shlex.quote(perm),
        )
        if returncode == 0 and stdout.strip():
            for line in stdout.strip().splitlines():
                if "[" in line and "]" in line:
                    bool_start = line.index("[") + 1
                    bool_end = line.index("]")
                    bool_name = line[bool_start:bool_end].split(":")[0].strip()
                    if bool_name:
                        rules_count = 1
                        risk_score = _score_boolean(rules_count, 1)
                        risk = {
                            "risk_score": risk_score,
                            "risk_level": "low" if risk_score <= 25 else "medium",
                            "recommendation": "proceed" if risk_score <= 25 else "proceed_with_review",
                        }
                        play = _playbook_header(f"Enable {bool_name} for {source} → {target}")
                        play["roles"] = [{
                            "role": f"{SYSTEM_ROLES_COLLECTION}.selinux",
                            "vars": {
                                "selinux_booleans": [{
                                    "name": bool_name,
                                    "state": "on",
                                    "persistent": True,
                                }],
                            },
                        }]
                        alternatives.append({
                            "strategy": "boolean",
                            "scope": f"medium — enables boolean {bool_name}",
                            "boolean": bool_name,
                            "risk": risk,
                            "playbook": _render_playbook(
                                play, f"Enable boolean {bool_name}", risk,
                            ),
                        })
    except Exception:
        pass  # sesearch not available — skip boolean option

    # Custom CIL module (broadest)
    cil_content = f"(allow {source} {target} ({cls} ({perm})))"
    module_risk_score = _score_module(target, perm)
    module_risk = {
        "risk_score": module_risk_score,
        "risk_level": "low" if module_risk_score <= 25 else "medium" if module_risk_score <= 50 else "high",
        "recommendation": "proceed" if module_risk_score <= 25 else "proceed_with_review",
    }
    module_play = _playbook_header(f"Load CIL module for {source} → {target}:{perm}")
    module_play["roles"] = [{
        "role": f"{SYSTEM_ROLES_COLLECTION}.selinux",
        "vars": {
            "selinux_modules": [{
                "name": f"fix_{source}_{perm}",
                "state": "enabled",
                "content": cil_content,
                "priority": "400",
            }],
        },
    }]
    alternatives.append({
        "strategy": "custom_module",
        "scope": "narrow — single allow rule",
        "risk": module_risk,
        "playbook": _render_playbook(
            module_play,
            f"Custom CIL module: {source} → {target}:{perm}",
            module_risk,
        ),
    })

    alternatives.sort(key=lambda a: a["risk"].get("risk_score", 999))
    return {
        "finding_type": "denial",
        "recommended": alternatives[0],
        "alternatives": alternatives,
        "total_options": len(alternatives),
    }


def _remediate_file_context(
    path: str | None,
    expected_type: str | None,
    actual_type: str | None,
) -> dict:
    if not path:
        return {"error": "missing_params", "required": ["path"]}

    try:
        validate_path(path)
        if expected_type:
            _validate_selinux_identifier(expected_type, "expected_type")
        if actual_type:
            _validate_selinux_identifier(actual_type, "actual_type")
    except ValueError as e:
        return {"error": "invalid_input", "detail": str(e)}

    alternatives = []

    if expected_type and actual_type and expected_type != actual_type:
        play = _playbook_header(f"Restore context on {path}")
        play["roles"] = [{
            "role": f"{SYSTEM_ROLES_COLLECTION}.selinux",
            "vars": {"selinux_restore_dirs": [path]},
        }]
        risk = {
            "risk_score": 5, "risk_level": "low",
            "recommendation": "proceed",
            "reversibility": {"method": "restorecon is idempotent", "difficulty": "easy"},
        }
        alternatives.append({
            "strategy": "restorecon",
            "scope": "narrowest — relabels to expected context",
            "risk": risk,
            "playbook": _render_playbook(
                play, f"Restore {path} from {actual_type} to {expected_type}", risk,
            ),
        })

    if expected_type:
        play = _playbook_header(f"Set file context {expected_type} on {path}")
        play["roles"] = [{
            "role": f"{SYSTEM_ROLES_COLLECTION}.selinux",
            "vars": {
                "selinux_fcontexts": [{
                    "target": path, "setype": expected_type, "state": "present",
                }],
                "selinux_restore_dirs": [path],
            },
        }]
        risk = {
            "risk_score": 15, "risk_level": "low",
            "recommendation": "proceed",
            "reversibility": {
                "method": f"semanage fcontext -d '{path}'", "difficulty": "easy",
            },
        }
        alternatives.append({
            "strategy": "fcontext_rule",
            "scope": "permanent — survives relabel",
            "risk": risk,
            "playbook": _render_playbook(play, f"Permanent context rule for {path}", risk),
        })

    alternatives.sort(key=lambda a: a["risk"].get("risk_score", 999))
    return {
        "finding_type": "file_context",
        "recommended": alternatives[0] if alternatives else None,
        "alternatives": alternatives,
        "total_options": len(alternatives),
    }


def _remediate_fapolicyd(path: str | None) -> dict:
    if not path:
        return {"error": "missing_params", "required": ["path"]}

    try:
        validate_path(path)
    except ValueError as e:
        return {"error": "invalid_input", "detail": str(e)}

    risk = _score_fapolicyd_trust(path)
    play = _playbook_header(f"Trust {path} in fapolicyd")
    play["roles"] = [{
        "role": f"{SYSTEM_ROLES_COLLECTION}.fapolicyd",
        "vars": {"fapolicyd_add_trusted_paths": [path]},
    }]
    playbook_str = _render_playbook(play, f"Add {path} to fapolicyd trust", risk)

    return {
        "finding_type": "fapolicyd_block",
        "recommended": {
            "strategy": "trust_path", "scope": "single binary",
            "risk": risk, "playbook": playbook_str,
        },
        "alternatives": [{
            "strategy": "trust_path", "scope": "single binary",
            "risk": risk, "playbook": playbook_str,
        }],
        "total_options": 1,
    }


def _remediate_aide() -> dict:
    return {
        "finding_type": "aide_change",
        "action": "investigate",
        "message": (
            "AIDE detected changes. Investigate before accepting. "
            "Use the enforcement-mcp server for AIDE baseline management "
            "(aide_init_db, aide_update_db) which requires mutating access."
        ),
        "total_options": 0,
    }
